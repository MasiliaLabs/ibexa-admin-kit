import assert from 'node:assert/strict';
import { afterEach, test } from 'node:test';

import { adminHeaders, csrfToken, route } from './admin';

afterEach(() => {
    delete (globalThis as { Routing?: unknown }).Routing;
});

test('a route is generated by the admin\'s own router', () => {
    const calls: unknown[] = [];
    (globalThis as { Routing?: unknown }).Routing = { generate: (name: string, parameters: unknown) => { calls.push([name, parameters]); return `/admin/${name}`; } };

    assert.equal(route('masilia.sites.api.data', { id: 3 }), '/admin/masilia.sites.api.data');
    assert.deepEqual(calls, [['masilia.sites.api.data', { id: 3 }]]);
});

test('without the router of the admin, saying so is better than a wrong address', () => {
    assert.throws(() => route('masilia.sites.api.data'), /routes of the admin are not loaded: "masilia.sites.api.data"/);
});

test('without a page there is no token, and the headers still ask for JSON', () => {
    assert.equal(csrfToken(), '');
    assert.deepEqual(adminHeaders({ 'X-Extra': '1' }), { 'Content-Type': 'application/json', Accept: 'application/json', 'X-CSRF-Token': '', 'X-Extra': '1' });
});
